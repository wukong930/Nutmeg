"""δ₁ₓ₂ —— Pinnacle WPO 去vig 的 **1X2 三条腿**的判闸下界(2026-08-08)。

预注册 `docs/onex_delta_prereg_v1.0_2026-08-08.md`(先于测量提交,`e26a7a1`)。
测量  `docs/onex_delta_measurement_2026-08-08.md`。
复现  `python scripts/onex_delta_calibration.py`。

## 为什么存在

`market_handicap.c1_leg_lower_bounds` 只保护**让球重构**引入的 δ 误差,1X2 腿没有
重构这一步,所以它在服务端一直传 `lo=null` ⇒ 前端 `evLo ≡ ev`。而让球腿被收了
1.56–15.6pp。两类腿在**同一个 `evLo` 排序里竞争**(每场取 argmax 进串关池),
于是 1X2 腿拿到一个纯粹来自「没人给它算不确定性」的优势。

实测(6,516 场竞彩已结算欧洲比赛 / 871 个比赛日 / 比赛日聚类):

    主胜  δ̂ −0.37pp ± 0.58   t = −0.64
    平局  δ̂ −0.10pp ± 0.55   t = −0.18
    客胜  δ̂ +0.47pp ± 0.56   t = +0.85

⇒ **测不出偏差**(Pinnacle 校准得很好),所以**不出点估修正**。
⇒ 但 **SE 不为零**,下界照收 —— 这正是 `market_handicap._UNCAL_SE` 那段已经
   采纳过的立场:「没测过校准 ≠ 没有不确定性」。1X2 腿此前正是 `se=0`。

⚠️ **故意不把 δ̂ 带进下界**,尽管预注册 §6 字面允许 `lo = p + δ̂ − k·SE`。
   客胜 δ̂=+0.47 会把下界从 −1.11 **松到** −0.64 —— 让一个与噪声无法区分的正数去
   放松判闸,正是赢家诅咒的形状。与「+2 线不出点估、只拉宽下界」同一立场。

## 部署后实测到的行为(scripts/onex_argmax_flip.py)

每场 argmax **38.5%** 换了当选腿,1X2 占比 59.3% → 21.9%。原因不是收缩量大,是
两类腿本来就几乎打平(evLo 差中位 +0.62pp,67% 落在 ±2.9pp 内)。

**配对**检验(同一批比赛,不许拿两条独立 ROI 相减):
单腿 ΔROI −0.37pp ±1.17(t=−0.31)· 2串 +3.29 ±9.77 · 3串 +4.88 ±19.59
⇒ **收益上测不出差别。这是正确性修复,不是盈利修复。**

## ⚠️ 适用范围与借用

实测人口 = **9 个欧洲联赛**(英超/意甲/西甲/法甲/德甲/英冠/荷甲/葡超/法乙),
窗口止于 football-data 的 Pinnacle 死期 2026-01-14。逐联赛 Cochran's Q 测不出
异质(I² 0–14%,p 0.32–0.90),跨度从英超到法乙。

**日职 / 杯赛 / 北欧 / 韩职 / 美职 整个联赛 0 覆盖** —— 这些常数用在那里是
**借来的**,秋季必须重测。

⛔ 预注册 §6 原写「范围外吃 `_UNCAL_SE=0.078` 地板」,**部署时否决了**:那个
   0.078 是 **+2 让球线的重构误差**,和 1X2 是不同家族;k·SE 会变成 15.6pp,
   把范围外每条 1X2 腿抹平。而保持 `lo=p` 等于断言 **SE=0**,那是**确定错的**。
   两个都不完美的假设之间,选不是已知错的那个 ⇒ 全局用实测 SE。
   (这是对预注册的偏离,理由写在这里,不是悄悄改的。)
"""
from __future__ import annotations

# 三条腿各自的聚类 SE(实测,非猜测)。数量级几乎相同,但保留三个值而不是取平均 ——
# 与 `_C2_SE_H/_C2_SE_D/_C2_SE_A` 逐腿保留同一惯例:合并要有理由,不合并不需要。
ONEX_SE: tuple[float, float, float] = (0.0058, 0.0056, 0.0056)   # 主胜 / 平局 / 客胜

# 判闸的保守倍数(≈95% 单侧)。**必须**与 `market_handicap._C1_SE_K` 相同 ——
# 两类腿在同一个排序里竞争,k 不同就等于偷偷给一边加权。
# `tests/v4/test_onex_calibration.py` 钉住这条等式。
ONEX_SE_K = 2.0


def onex_leg_lower_bounds(
    p_home: float, p_draw: float, p_away: float, *, k: float = ONEX_SE_K,
) -> tuple[float, float, float]:
    """给 Pinnacle WPO 去vig 的 1X2 三元组,返回每条腿**自身**的判闸下界。

    保守方向是**逐腿**的:每条腿都取「让它自己的 P 更小」的那侧 = 点估 − k·SE。
    (δ̂ 不显著 ⇒ 点估不动,见模块 docstring。)

    ⚠️ **返回值不是概率分布**(和 < 1)—— 它是三个独立的单腿下界,**只用于判闸**,
    绝不可用于展示/归一化/喂模型。展示请用点估本身。
    与 `market_handicap.c1_leg_lower_bounds` 同一契约,故意长得一样。
    """
    return (
        max(float(p_home) - k * ONEX_SE[0], 0.0),
        max(float(p_draw) - k * ONEX_SE[1], 0.0),
        max(float(p_away) - k * ONEX_SE[2], 0.0),
    )


__all__ = ["ONEX_SE", "ONEX_SE_K", "onex_leg_lower_bounds"]
